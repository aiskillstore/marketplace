// Recovered copy with the deterministic corrections applied, for formats
// --fix refuses to touch: a PDF is a rendered page, so the corrections go
// into a NEW recovered-text file, never back into the document.
//
// The output is assembled from the scan's own copy units — the same spans the
// rules judged — with the fixable findings' replacements applied per unit and
// overlaps skipped rather than guessed. Everything a rule could not provably
// fix is left exactly as recovered: the file is a working copy of the text,
// not a silent rewrite of the document.

import { FIXABLE_RULE_IDS } from './fix.mjs';

/** The notice the recovered file opens with, kept as a masking-safe comment. */
export const RECOVERED_NOTICE = '<!-- Recovered text generated by un-editorial-check: the copy recovered from a PDF with the deterministic corrections applied. This is not an edit of the original document; check it against the source before use. -->';

/**
 * Build one PDF's corrected text.
 *
 * @param {Array} units     every unit the scan extracted
 * @param {Array} findings  the scan's findings (with _unit/_matched/_replacement)
 * @param {string} file     the PDF whose copy to rebuild
 * @returns {string} the recovered, corrected text
 */
export function buildCorrectedText(units, findings, file) {
  const byUnit = new Map();
  for (const finding of findings) {
    if (!finding._replacement || !finding._unit) continue;
    if (!FIXABLE_RULE_IDS.has(finding.ruleId)) continue;
    if (finding._unit.file !== file) continue;
    const unit = finding._unit;
    if (!byUnit.has(unit)) byUnit.set(unit, []);
    byUnit.get(unit).push({
      start: finding._index,
      end: finding._index + (finding._matched || '').length,
      replacement: finding._replacement,
      ruleId: finding.ruleId,
    });
  }

  const lines = [];
  let lastPage = null;
  for (const unit of units) {
    if (unit.file !== file) continue;
    if (lastPage !== null && unit.pdfPage !== lastPage) lines.push('');
    lastPage = unit.pdfPage;
    let text = unit.text;
    const edits = (byUnit.get(unit) || [])
      .slice()
      .sort((a, b) => b.start - a.start);
    let cursor = Infinity;
    for (const edit of edits) {
      // Overlaps and zero-length matches are skipped, never guessed at; a
      // start outside the text means the finding and the unit disagree, so
      // the whole unit is left as recovered.
      if (edit.end > cursor || edit.start < 0 || edit.end > text.length) continue;
      text = text.slice(0, edit.start) + edit.replacement + text.slice(edit.end);
      cursor = edit.start;
    }
    lines.push(text);
  }
  return `${RECOVERED_NOTICE}\n\n${lines.join('\n')}\n`;
}
