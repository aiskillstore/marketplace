#!/usr/bin/env python3
"""Generate technical .cube LUTs from built-in color science transforms."""

from __future__ import annotations

import argparse
from pathlib import Path

from color_science_core import RGB_COLORSPACES, TRANSFER_NAMES, convert_rgb


def write_cube(args: argparse.Namespace) -> None:
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    title = args.title or f"{args.source_space}-{args.source_transfer}_to_{args.target_space}-{args.target_transfer}"
    scale = args.size - 1
    with output.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(f'TITLE "{title.replace(chr(34), chr(39))}"\n')
        handle.write("# Generated by generate-lut technical color science tools.\n")
        handle.write(f"# Source: {args.source_space} / {args.source_transfer}\n")
        handle.write(f"# Target: {args.target_space} / {args.target_transfer}\n")
        handle.write(f"# Tone map: {args.tone_map}\n")
        handle.write(f"# Exposure stops: {args.exposure:.6f}\n")
        handle.write("DOMAIN_MIN 0.0 0.0 0.0\n")
        handle.write("DOMAIN_MAX 1.0 1.0 1.0\n")
        handle.write(f"LUT_3D_SIZE {args.size}\n\n")
        for b in range(args.size):
            for g in range(args.size):
                for r in range(args.size):
                    rgb = (r / scale, g / scale, b / scale)
                    out = convert_rgb(
                        rgb,
                        args.source_space,
                        args.source_transfer,
                        args.target_space,
                        args.target_transfer,
                        args.source_peak_nits,
                        args.target_peak_nits,
                        args.exposure,
                        args.tone_map,
                        not args.no_clamp,
                    )
                    handle.write(f"{out[0]:.7f} {out[1]:.7f} {out[2]:.7f}\n")
    print(f"Wrote {output}")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate a technical .cube 3D LUT.")
    parser.add_argument("--output", required=True, help="Path to write .cube LUT.")
    parser.add_argument("--size", type=int, default=33, help="3D LUT size, commonly 17, 33, or 65.")
    parser.add_argument("--source-space", choices=sorted(RGB_COLORSPACES), required=True, help="Source RGB primaries.")
    parser.add_argument("--source-transfer", choices=TRANSFER_NAMES, required=True, help="Source transfer function.")
    parser.add_argument("--target-space", choices=sorted(RGB_COLORSPACES), required=True, help="Target RGB primaries.")
    parser.add_argument("--target-transfer", choices=TRANSFER_NAMES, required=True, help="Target transfer function.")
    parser.add_argument("--source-peak-nits", type=float, default=1000.0, help="Reference peak for PQ source decoding.")
    parser.add_argument("--target-peak-nits", type=float, default=1000.0, help="Reference peak for PQ target encoding.")
    parser.add_argument("--tone-map", choices=("none", "reinhard", "luminance-reinhard"), default="none", help="Optional highlight compression.")
    parser.add_argument("--exposure", type=float, default=0.0, help="Exposure offset in stops before target encoding.")
    parser.add_argument("--title", default=None, help="Optional LUT title.")
    parser.add_argument("--no-clamp", action="store_true", help="Do not clamp output values to 0..1.")
    args = parser.parse_args()
    if args.size < 2 or args.size > 128:
        parser.error("--size must be between 2 and 128")
    if args.source_peak_nits <= 0 or args.target_peak_nits <= 0:
        parser.error("Peak nit values must be positive")
    return args


def main() -> None:
    write_cube(parse_args())


if __name__ == "__main__":
    main()
