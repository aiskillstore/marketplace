#!/usr/bin/env python3
"""Bake a .cube LUT through an OpenColorIO config when PyOpenColorIO is installed."""

from __future__ import annotations

import argparse
from pathlib import Path


def load_ocio():
    try:
        import PyOpenColorIO as ocio  # type: ignore
    except ImportError as exc:
        raise SystemExit(
            "PyOpenColorIO is not installed. Install it in the active Python environment "
            "or use generate_technical_lut.py for built-in transforms."
        ) from exc
    return ocio


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Bake a .cube LUT with OpenColorIO.")
    parser.add_argument("--config", required=True, help="Path to an OCIO config file.")
    parser.add_argument("--source", required=True, help="Source color space or role in the OCIO config.")
    parser.add_argument("--target", required=True, help="Target color space or role in the OCIO config.")
    parser.add_argument("--output", required=True, help="Path to write .cube LUT.")
    parser.add_argument("--size", type=int, default=33, help="3D LUT size.")
    parser.add_argument("--title", default=None, help="Optional LUT title.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    if args.size < 2 or args.size > 128:
        raise SystemExit("--size must be between 2 and 128")
    ocio = load_ocio()
    config = ocio.Config.CreateFromFile(args.config)
    processor = config.getProcessor(args.source, args.target)
    cpu = processor.getDefaultCPUProcessor()
    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    title = args.title or f"ocio_{args.source}_to_{args.target}"
    scale = args.size - 1
    with output.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(f'TITLE "{title.replace(chr(34), chr(39))}"\n')
        handle.write("# Generated by generate-lut OpenColorIO bridge.\n")
        handle.write(f"# OCIO config: {args.config}\n")
        handle.write(f"# Source: {args.source}\n")
        handle.write(f"# Target: {args.target}\n")
        handle.write("DOMAIN_MIN 0.0 0.0 0.0\n")
        handle.write("DOMAIN_MAX 1.0 1.0 1.0\n")
        handle.write(f"LUT_3D_SIZE {args.size}\n\n")
        for b in range(args.size):
            for g in range(args.size):
                for r in range(args.size):
                    rgb = [r / scale, g / scale, b / scale]
                    cpu.applyRGB(rgb)
                    handle.write(f"{rgb[0]:.7f} {rgb[1]:.7f} {rgb[2]:.7f}\n")
    print(f"Wrote {output}")


if __name__ == "__main__":
    main()
